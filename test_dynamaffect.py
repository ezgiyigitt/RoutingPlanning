@test("Patent: Dynamic Weighting Function w(ASI)")
def test_dynamic_weighting():
    """
    w(ASI) fonksiyonunun matematiksel do??rulu??u
    """
    from dynamaffect_core import DynamicWeightingFunction
    
    # Test extreme cases
    asi_values = [-1.0, -0.5, 0.0, 0.5, 1.0]
    
    for asi in asi_values:
        w1, w2, w3 = DynamicWeightingFunction.calculate_weights(asi)
        
        # Weights should sum to ~1.0 (normalized)
        total = w1 + w2 + w3
        assert 0.9 < total < 1.1, f"Weights don't normalize: {w1}, {w2}, {w3}"
        
        # Individual weights should be positive
        assert w1 > 0 and w2 > 0 and w3 > 0
    
    # Verify w1 decreases, w3 increases with ASI
    w1_low, _, w3_low = DynamicWeightingFunction.calculate_weights(-1.0)
    w1_high, _, w3_high = DynamicWeightingFunction.calculate_weights(1.0)
    
    assert w1_high < w1_low, "w1 should decrease with ASI"
    assert w3_high > w3_low, "w3 should increase with ASI"
    
    print(f"  -> ASI=-1: w1={w1_low:.2f}, w3={w3_low:.2f}")
    print(f"  -> ASI=+1: w1={w1_high:.2f}, w3={w3_high:.2f}")


