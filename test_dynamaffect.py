@test("Q-Learning: State Action Update")
def test_qlearning_update():
    """
    Q-Learning tablosu g??ncelleme mant??????
    """
    from dynamaffect_qlearning import DriverQNetwork, QState, QAction, RewardSignal
    
    network = DriverQNetwork(driver_id="test_driver")
    
    # Create a state
    state = QState(
        origin="K??z??lay",
        destination="Hacettepe",
        asi=-0.3,
        time_of_day=14,
        weather="clear",
        route_type="balanced"
    )
    
    # Select action
    action = network.select_action(state, exploit=True)
    assert action in QAction.ALL
    
    # Get initial Q-value
    initial_q = network.get_best_action_value(state)
    
    # Update with reward
    reward_signal = RewardSignal(
        completed=True,
        early_exit=False,
        driver_feedback=5.0,
        harsh_accel=False,
        traffic_incident=False,
        time_efficiency=1.0
    )
    reward = reward_signal.calculate_reward()
    
    network.update_q(state, action, reward)
    
    # Q-value should have changed
    new_q = network.get_best_action_value(state)
    assert new_q != initial_q, "Q-value should update"
    
    print(f"  -> Initial Q: {initial_q:.2f}, After update: {new_q:.2f}")
    print(f"  -> Reward signal: {reward:.2f}")


