@test("ASI: Stress Detection (High EDA)")
def test_asi_stressed():
    from dynamaffect_core import AffectStateTensor, AffectStateCalculator
    
    calc = AffectStateCalculator()
    
    # High stress parameters
    cls = calc.calculate_cls(
        pupil_dilation=70,
        steering_variance=50,
        traffic_density=0.8,
        lane_clarity=0.3,
        weather_severity=0.6
    )
    
    ev = calc.calculate_ev(
        au12=0.1,    # Low smile
        au15=0.3,    # Sadness
        au4=0.4,     # Anger
        eda_level=0.8
    )
    
    psi = AffectStateTensor(
        cls_t=cls,
        ev_t=ev,
        fa_t=0.5,
        pr_t=0.5
    )
    
    asi = calc.calculate_asi(psi)
    
    # Should be negative (stressed)
    assert asi < -0.3, f"Expected ASI < -0.3, got {asi}"
    category = calc.get_stress_category(asi)
    assert "STRESS" in category, f"Expected stressed category, got {category}"

